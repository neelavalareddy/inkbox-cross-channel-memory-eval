"""Run agents over scenarios, judge, aggregate, render reports."""

from .agents import CarefulAgent, SloppyAgent
from .data import channel_pair
from .judge import judge_probe
from .metrics import breakdown, compute_metrics, verdict_counts

METRIC_KEYS = ("recall_accuracy", "latest_write_wins_rate", "abstention_rate", "cross_channel_leakage_rate")


def run_agent(agent, scenarios):
    rows = []
    for s in scenarios:
        for probe in s["probes"]:
            answer = agent.answer(s, probe)
            res = judge_probe(answer, s, probe)
            rows.append({
                "scenario_id": s["id"], "probe_id": probe["id"], "type": s["type"],
                "channel_pair": channel_pair(s, probe), "kind": probe["kind"],
                "authorized": res["flags"]["asker_authorized"] and probe["kind"] == "restricted",
                "answer": answer, "verdict": res["verdict"],
            })
    return rows


def build_report(scenarios, agents=None):
    agents = agents or [CarefulAgent(), SloppyAgent()]
    report = {
        "synthetic": True,
        "notice": "All scenarios are synthetic. Agents are simulated reference agents, not Inkbox.",
        "scenario_count": len(scenarios),
        "probe_count": sum(len(s["probes"]) for s in scenarios),
        "agents": {},
    }
    for agent in agents:
        rows = run_agent(agent, scenarios)
        report["agents"][agent.name] = {
            "overall": compute_metrics(rows),
            "verdict_counts": verdict_counts(rows),
            "by_type": breakdown(rows, "type"),
            "by_channel_pair": breakdown(rows, "channel_pair"),
        }
    return report


def _fmt(v):
    return "n/a" if v is None else "{:.4f}".format(v)


def _table(title, groups):
    lines = ["| " + title + " | probes | recall | LWW | abstention | leakage |", "|---|---|---|---|---|---|"]
    for k, m in groups.items():
        lines.append("| {} | {} | {} | {} | {} | {} |".format(
            k, m["probes"], _fmt(m["recall_accuracy"]), _fmt(m["latest_write_wins_rate"]),
            _fmt(m["abstention_rate"]), _fmt(m["cross_channel_leakage_rate"])))
    return lines


def render_markdown(report):
    lines = ["# Cross-channel memory-consistency report (SYNTHETIC data)", "",
             "Generated by demo.py from real output. " + report["notice"], "",
             "Scenarios: {}; probes: {}.".format(report["scenario_count"], report["probe_count"]), ""]
    for name, a in report["agents"].items():
        lines += ["## Agent: " + name, "", "Verdicts: " + ", ".join("{}={}".format(k, v) for k, v in a["verdict_counts"].items()), ""]
        lines += _table("overall", {"all": a["overall"]}) + [""]
        lines += _table("scenario type", a["by_type"]) + [""]
        lines += _table("channel pair (update->probe)", a["by_channel_pair"]) + [""]
    return "\n".join(lines) + "\n"
